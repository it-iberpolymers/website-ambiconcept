// Converte **negrito** (markdown simples) em <strong> — usado só no texto dos ODS.
function renderBold(text: string): ReactNode[] {
  return text.split(/\*\*(.+?)\*\*/g).map((part, i) => (i % 2 === 1 ? <strong key={i}>{part}</strong> : part))
}

// Desloca a imagem até ±maxPx conforme a distância do centro do ecrã —
// mesmo padrão de scroll + requestAnimationFrame das animações de scroll dos templates de produto.
function useParallax(strength = 0.15, maxPx = 60) {
  const ref = useRef<HTMLDivElement>(null)
  const [offset, setOffset] = useState(0)

  useEffect(() => {
    let ticking = false
    function update() {
      ticking = false
      const el = ref.current
      if (!el) return
      const rect = el.getBoundingClientRect()
      const distanceFromCenter = rect.top + rect.height / 2 - window.innerHeight / 2
      setOffset(Math.max(-maxPx, Math.min(maxPx, distanceFromCenter * -strength)))
    }
    function onScroll() {
      if (!ticking) {
        ticking = true
        window.requestAnimationFrame(update)
      }
    }
    window.addEventListener('scroll', onScroll, { passive: true })
    update()
    return () => window.removeEventListener('scroll', onScroll)
  }, [strength, maxPx])

  return [ref, offset] as const
}

function easeOutCubic(t: number) {
  return 1 - Math.pow(1 - t, 3)
}

// Conta de 0 até `target` quando o elemento entra no ecrã — mesma lógica do
// AnimatedCounter, sem o layout próprio dele (aqui o número é só uma peça do cartão).
function useCountUp(target: number, duration = 1800) {
  const ref = useRef<HTMLParagraphElement>(null)
  const [count, setCount] = useState(0)
  const [started, setStarted] = useState(false)

  useEffect(() => {
    const el = ref.current
    if (!el) return
    const observer = new IntersectionObserver(
      ([entry]) => { if (entry.isIntersecting) setStarted(true) },
      { threshold: 0.3 }
    )
    observer.observe(el)
    return () => observer.disconnect()
  }, [])

  useEffect(() => {
    if (!started) return
    const startTime = performance.now()
    let raf: number
    function tick(now: number) {
      const progress = Math.min((now - startTime) / duration, 1)
      setCount(Math.round(easeOutCubic(progress) * target))
      if (progress < 1) raf = requestAnimationFrame(tick)
    }
    raf = requestAnimationFrame(tick)
    return () => cancelAnimationFrame(raf)
  }, [started, target, duration])

  return [ref, count] as const
}

// Roda continuamente para a direita conforme o scroll da página (não fica
// limitado à posição do elemento — é o scroll da página toda que conta).
function useScrollRotation(degreesPerPixel = 0.3) {
  const [rotation, setRotation] = useState(0)

  useEffect(() => {
    let ticking = false
    function update() {
      ticking = false
      setRotation(window.scrollY * degreesPerPixel)
    }
    function onScroll() {
      if (!ticking) {
        ticking = true
        window.requestAnimationFrame(update)
      }
    }
    window.addEventListener('scroll', onScroll, { passive: true })
    update()
    return () => window.removeEventListener('scroll', onScroll)
  }, [degreesPerPixel])

  return rotation
}

function ImpactStat({ stat }: { stat: FlowImpactStat }) {
  const [countRef, count] = useCountUp(stat.target)
  const rotation = useScrollRotation(0.1)
  const iconStyle = stat.icon === 'recycle' ? { transform: `rotate(${rotation}deg)` } : undefined
  return (
    <div className="fl-impact-stat">
      <span className="fl-impact-stat-icon" style={iconStyle}>{IMPACT_ICONS[stat.icon]}</span>
      <p ref={countRef} className="fl-impact-stat-value">
        {stat.prefix ?? ''}{count.toLocaleString('pt-PT')}{stat.suffix ?? ''}
      </p>
      <p className="fl-impact-stat-label">{stat.label}</p>
      <p className="fl-impact-stat-desc">{stat.description}</p>
    </div>
  )
}

